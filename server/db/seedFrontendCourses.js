const COURSES = [HTML_COURSE, CSS_COURSE, JS_COURSE];

// ── Insert ──────────────────────────────────────────────────────────────────

export function seedFrontendCourses(db) {
  db.exec(`
    CREATE TABLE IF NOT EXISTS seed_markers (
      key TEXT PRIMARY KEY,
      applied_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);
  if (db.prepare('SELECT 1 FROM seed_markers WHERE key = ?').get(MARKER)) return;

  // A lead, so the byline reads as a lead's course — which is the whole
  // point of these three. No lead yet (a brand-new install mid-setup) means
  // no author: leave the marker unset so this runs again once there is one.
  const author = db.prepare(
    "SELECT id FROM users WHERE role IN ('lead','admin') AND archived_at IS NULL ORDER BY CASE role WHEN 'lead' THEN 0 ELSE 1 END, id LIMIT 1"
  ).get();
  if (!author) return;
  const by = author.id;

  const insertAll = db.transaction(() => {
    const existing = db.prepare('SELECT 1 FROM custom_courses WHERE title = ? AND deleted_at IS NULL');
    const insCourse = db.prepare(`
      INSERT INTO custom_courses (title, description, tag, color, requirements, is_published, created_by, updated_at, success_text, fail_text)
      VALUES (?, ?, ?, ?, ?, 1, ?, ?, ?, ?)
    `);
    const insModule = db.prepare('INSERT INTO custom_modules (course_id, title, order_num) VALUES (?, ?, ?)');
    const insLesson = db.prepare(`
      INSERT INTO custom_lessons (module_id, title, type, content, order_num, prerequisite_type, prerequisite_lesson_id)
      VALUES (?, ?, ?, ?, ?, ?, ?)
    `);
    const insQuestion = db.prepare(`
      INSERT INTO custom_quiz_questions (lesson_id, question_text, option_a, option_b, option_c, option_d, correct_idx, explanation, order_num)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    const now = new Date().toISOString();
    for (const c of COURSES) {
      // A course with this title already in the catalog means someone has
      // it — hand-made or from an earlier run of the old one-off migration.
      // Adding a second copy beside it would be worse than adding nothing.
      if (existing.get(c.title)) continue;

      const courseId = insCourse.run(
        c.title, c.description, c.tag, c.color, c.requirements, by, now, c.success_text, c.fail_text
      ).lastInsertRowid;

      // Each module opens only after the previous module's test has been
      // taken, which is what makes the intermediate tests intermediate
      // rather than optional detours. The first module is never gated.
      let previousQuizId = null;

      c.modules.forEach((m, mi) => {
        const moduleId = insModule.run(courseId, m.title, mi).lastInsertRowid;

        m.lessons.forEach((l, li) => {
          const gate = li === 0 && previousQuizId !== null;
          const lessonId = insLesson.run(
            moduleId, l.title, l.type === 'quiz' ? 'quiz' : 'lesson', l.content || '', li,
            gate ? 'mandatory' : 'none', gate ? previousQuizId : null
          ).lastInsertRowid;

          if (l.type === 'quiz') {
            (l.questions || []).forEach((qq, qi) => insQuestion.run(
              lessonId, qq.text, qq.options[0], qq.options[1], qq.options[2], qq.options[3],
              qq.correct, qq.explanation, qi
            ));
            previousQuizId = lessonId;
          }
        });
      });

      // Published courses show up in the feed the same way a hand-published
      // one does, rather than appearing out of nowhere in the catalog.
      db.prepare("INSERT INTO team_events (event_type, user_id, ref_id) VALUES ('course_published', ?, ?)").run(by, courseId);
    }

    db.prepare('INSERT INTO seed_markers (key) VALUES (?)').run(MARKER);
  });

  insertAll();
}
