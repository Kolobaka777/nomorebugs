// ── Insert ─────────────────────────────────────────────────────────────────

export function seedDemoContent(db) {
  db.exec(`
    CREATE TABLE IF NOT EXISTS seed_markers (
      key TEXT PRIMARY KEY,
      applied_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
  `);
  if (db.prepare('SELECT 1 FROM seed_markers WHERE key = ?').get(MARKER)) return;

  // Attributed to a real person, so bylines, the author filter and the news
  // feed all behave exactly as they would for hand-written content. No lead
  // yet (a brand-new install mid-setup) means no author — leave the marker
  // unset so this runs again once there is one.
  const author = db.prepare(
    "SELECT id FROM users WHERE role IN ('lead','admin') AND archived_at IS NULL ORDER BY CASE role WHEN 'lead' THEN 0 ELSE 1 END, id LIMIT 1"
  ).get();
  if (!author) return;
  const by = author.id;

  const insertAll = db.transaction(() => {
    const insCourse = db.prepare(`
      INSERT INTO custom_courses (title, description, tag, color, requirements, is_published, created_by, updated_at, success_text, fail_text)
      VALUES (?, ?, ?, ?, ?, 1, ?, ?, ?, ?)
    `);
    const insModule = db.prepare('INSERT INTO custom_modules (course_id, title, order_num) VALUES (?, ?, 0)');
    const insLesson = db.prepare("INSERT INTO custom_lessons (module_id, title, type, content, order_num, prerequisite_type) VALUES (?, ?, 'quiz', '', 0, 'none')");
    const insQuestion = db.prepare(`
      INSERT INTO custom_quiz_questions (lesson_id, question_text, option_a, option_b, option_c, option_d, correct_idx, explanation, order_num)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    const now = new Date().toISOString();
    for (const c of COURSES) {
      const courseId = insCourse.run(
        c.title, c.description, c.tag, c.color, c.requirements, by, now, c.success_text, c.fail_text
      ).lastInsertRowid;
      const moduleId = insModule.run(courseId, 'Вопросы').lastInsertRowid;
      const lessonId = insLesson.run(moduleId, c.title).lastInsertRowid;
      c.questions.forEach((q, i) => insQuestion.run(lessonId, q[0], q[1], q[2], q[3], q[4], q[5], q[6], i));
      // Published courses show up in the feed the same way a hand-published
      // one does, rather than appearing out of nowhere in the catalog.
      db.prepare("INSERT INTO team_events (event_type, user_id, ref_id) VALUES ('course_published', ?, ?)").run(by, courseId);
    }

    const insGuide = db.prepare('INSERT INTO guides (title, category, content, created_by) VALUES (?, ?, ?, ?)');
    for (const g of GUIDES) insGuide.run(g.title, g.category, g.content, by);

    const insExample = db.prepare('INSERT INTO bug_examples (tag, tag_color, problem, bad_text, good_text, created_by) VALUES (?, ?, ?, ?, ?, ?)');
    for (const e of BUG_EXAMPLES) insExample.run(e.tag, e.tag_color, e.problem, e.bad_text, e.good_text, by);

    const insTerm = db.prepare('INSERT INTO glossary_terms (term, definition, created_by) VALUES (?, ?, ?)');
    for (const [term, definition] of GLOSSARY) insTerm.run(term, definition, by);

    db.prepare('INSERT INTO seed_markers (key) VALUES (?)').run(MARKER);
  });

  insertAll();
}
