// Demo content: ten joke quizzes, a handful of guides, bug examples and
// glossary terms, so a fresh install has something to click on instead of
// eleven empty pages.
//
// Everything here is attributed to the team's lead, not to a synthetic
// "system" account — the point is that it reads as though a person put it
// there, and every byline, news item and author filter already works off a
// real user id.
//
// Seeded exactly once, tracked in seed_markers. Not guarded on "is the
// table empty" like the older seeds in schema.js: these are disposable
// jokes and a lead deleting them should keep them deleted, which a
// content-shaped guard can't express — it would helpfully put them back on
// the next restart.
//
// The quizzes are deliberately silly. They exist to be handed to real
// people as something harmless to poke at, and a course about prison
// etiquette or Winx fairies gets that done better than a tenth quiz about
// HTML. Several of them are office manners wearing a costume.

